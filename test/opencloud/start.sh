#!/usr/bin/env bash
# Idempotent launcher for a throwaway OpenCloud (rolling 9.2.0) used by WebDAV integration tests.
#
#   ./start.sh            start (or keep running) on plain HTTP  http://127.0.0.1:9200   (default)
#   OC_TLS=1 ./start.sh   start on HTTPS with OpenCloud's self-signed cert  https://localhost:9200
#   RESET=1 ./start.sh    wipe config + data first (fresh instance, new user + token)
#
# Writes ./env with SHIORI_DAV_URL / SHIORI_DAV_USER / SHIORI_DAV_TOKEN (+ SHIORI_DAV_INSECURE / SHIORI_DAV_CA for TLS).
# NOTE: app tokens contain spaces, so SHIORI_DAV_TOKEN is written double-quoted (works with `source`, dotenv, node --env-file).
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN="$DIR/bin/opencloud"
RUN="$DIR/run"
PIDFILE="$RUN/opencloud.pid"
LOG="$RUN/server.log"
ENVFILE="$DIR/env"
ADMIN_TOKEN_FILE="$RUN/admin-token"

PORT="${OC_PORT:-9200}"
DAV_USER="${SHIORI_TEST_USER:-shiori}"
# Password is only used to create the account. Password Basic auth is disabled (PROXY_ENABLE_BASIC_AUTH unset),
# exactly like a default OpenCloud deployment, so clients must use the app token.
DAV_PASS="${SHIORI_TEST_PASS:-ShioriPass123!}"
ADMIN_PASS="admin"
TOKEN_TTL="${SHIORI_TOKEN_TTL:-8760h}"

# Pinned image: opencloudeu/opencloud-rolling:9.2.0 (linux/amd64), last layer = /usr/bin/opencloud only.
IMAGE_REPO="opencloudeu/opencloud-rolling"
BIN_LAYER="sha256:c62127ef807c76a56fa88e8520ff014075a5b8203a8a04c8cad6279bc92db8d3"

export NO_PROXY="localhost,127.0.0.1${NO_PROXY:+,$NO_PROXY}" no_proxy="localhost,127.0.0.1${no_proxy:+,$no_proxy}"
CURL=(curl --noproxy '*' -s --max-time 20)

log() { echo "[start.sh] $*" >&2; }

if [ "${OC_TLS:-0}" = "1" ]; then
  MODE=https
  BASE="https://localhost:$PORT"
  CA="$DIR/data/proxy/server.crt"   # generated by the proxy on first TLS start
  CURL+=(--cacert "$CA")
else
  MODE=http
  BASE="http://127.0.0.1:$PORT"
fi

export OC_CONFIG_DIR="$DIR/config"
export OC_BASE_DATA_PATH="$DIR/data"
export OC_URL="$BASE"
export OC_INSECURE=true                  # internal service-to-service TLS checks (self-signed)
export PROXY_HTTP_ADDR="127.0.0.1:$PORT"
export OC_LOG_LEVEL="${OC_LOG_LEVEL:-warn}"
if [ "$MODE" = http ]; then
  export PROXY_TLS=false
  # The built-in IDP refuses a non-https issuer ("invalid iss value, URL must start with https://")
  # and that error is fatal for the whole runtime -> drop it. Not needed for Basic/app-token auth.
  export OC_EXCLUDE_RUN_SERVICES=idp
fi
# auth-app is in the default service list of 9.x and PROXY_ENABLE_APP_AUTH defaults to on -> nothing to set.

fetch_binary() {
  log "fetching opencloud binary from registry-1.docker.io ($IMAGE_REPO, layer $BIN_LAYER)"
  local tmp; tmp="$(mktemp -d "$DIR/.fetch.XXXXXX")"
  local tok
  tok="$(curl -fsS "https://auth.docker.io/token?service=registry.docker.io&scope=repository:$IMAGE_REPO:pull" |
         python3 -I -c 'import sys,json;print(json.load(sys.stdin)["token"])')"
  curl -fsSL -H "Authorization: Bearer $tok" -o "$tmp/layer.tgz" \
    "https://registry-1.docker.io/v2/$IMAGE_REPO/blobs/$BIN_LAYER"
  echo "${BIN_LAYER#sha256:}  $tmp/layer.tgz" | sha256sum -c - >/dev/null
  mkdir -p "$tmp/x" "$DIR/bin"
  tar xzf "$tmp/layer.tgz" -C "$tmp/x" usr/bin/opencloud
  install -m 0755 "$tmp/x/usr/bin/opencloud" "$BIN"
  rm -rf "$tmp"
}

is_running() { [ -f "$PIDFILE" ] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; }

status_ok() { [ "$("${CURL[@]}" -o /dev/null -w '%{http_code}' "$BASE/status.php" || true)" = 200 ]; }

dav_ok() { # user token -> 0 if PROPFIND on personal root is 207
  [ "$("${CURL[@]}" -o /dev/null -w '%{http_code}' -u "$1:$2" -X PROPFIND -H 'Depth: 0' "$BASE/remote.php/webdav/" || true)" = 207 ]
}

create_token() { # user -> prints token (retries while services are still coming up)
  local out i
  for i in $(seq 1 40); do
    if out="$("$BIN" auth-app create --user-name "$1" --expiration "$TOKEN_TTL" 2>&1)"; then
      out="$(printf '%s\n' "$out" | sed -n 's/^ *token: //p')"
      if [ -n "$out" ]; then printf '%s' "$out"; return 0; fi
    fi
    sleep 1
  done
  log "could not create app token for $1: $out"; return 1
}

# ---------------------------------------------------------------------------
[ -x "$BIN" ] || fetch_binary
mkdir -p "$RUN"

if [ "${RESET:-0}" = "1" ]; then
  log "RESET=1: stopping and wiping config/data"
  "$DIR/stop.sh" || true
  rm -rf "$DIR/config" "$DIR/data" "$RUN" "$ENVFILE"
  mkdir -p "$RUN"
fi

if is_running && [ "$(cat "$RUN/mode" 2>/dev/null)" != "$MODE" ]; then
  log "running in mode '$(cat "$RUN/mode" 2>/dev/null)', requested '$MODE' -> restarting"
  "$DIR/stop.sh"
fi

if [ ! -f "$OC_CONFIG_DIR/opencloud.yaml" ]; then
  log "opencloud init"
  mkdir -p "$OC_CONFIG_DIR" "$OC_BASE_DATA_PATH"
  "$BIN" init --config-path "$OC_CONFIG_DIR" --insecure true --admin-password "$ADMIN_PASS" -q >/dev/null
fi

if is_running && status_ok; then
  log "already running (pid $(cat "$PIDFILE")) at $BASE"
else
  if is_running; then "$DIR/stop.sh"; fi
  log "starting opencloud server ($MODE) -> $LOG"
  echo "$MODE" > "$RUN/mode"
  setsid bash -c 'echo $$ > "$1"; shift; exec "$@"' _ "$PIDFILE" "$BIN" server >>"$LOG" 2>&1 </dev/null &
  for i in $(seq 1 90); do
    sleep 1
    is_running || { log "server exited; tail of $LOG:"; tail -20 "$LOG" >&2; exit 1; }
    status_ok && break
  done
  status_ok || { log "server not healthy after 90s"; exit 1; }
fi

# --- admin app token (used only to manage users via the Graph API) ---
ADMIN_TOKEN="$(cat "$ADMIN_TOKEN_FILE" 2>/dev/null || true)"
retry_dav() { for i in $(seq 1 "$3"); do dav_ok "$1" "$2" && return 0; sleep 1; done; return 1; }
if [ -z "$ADMIN_TOKEN" ] || ! retry_dav admin "$ADMIN_TOKEN" 5; then
  log "creating admin app token"
  ADMIN_TOKEN="$(create_token admin)"
  printf '%s' "$ADMIN_TOKEN" > "$ADMIN_TOKEN_FILE"; chmod 600 "$ADMIN_TOKEN_FILE"
  retry_dav admin "$ADMIN_TOKEN" 20 || { log "admin app token does not work"; exit 1; }
fi

# --- test user ---
code="$("${CURL[@]}" -o /dev/null -w '%{http_code}' -u "admin:$ADMIN_TOKEN" "$BASE/graph/v1.0/users/$DAV_USER")"
if [ "$code" = 404 ]; then
  log "creating user $DAV_USER"
  body="$(python3 -I -c 'import json,sys;u,p=sys.argv[1:3];print(json.dumps({"onPremisesSamAccountName":u,"displayName":"Shiori Test","mail":u+"@example.org","passwordProfile":{"password":p}}))' "$DAV_USER" "$DAV_PASS")"
  code="$("${CURL[@]}" -o "$RUN/user-create.json" -w '%{http_code}' -u "admin:$ADMIN_TOKEN" -X POST \
          -H 'Content-Type: application/json' --data-binary "$body" "$BASE/graph/v1.0/users")"
  [ "$code" = 201 ] || { log "user creation failed ($code): $(cat "$RUN/user-create.json")"; exit 1; }
elif [ "$code" != 200 ]; then
  log "unexpected status $code looking up user $DAV_USER"; exit 1
fi

# --- user app token (reuse the one in ./env if it still works) ---
DAV_TOKEN=""
if [ -f "$ENVFILE" ]; then
  DAV_TOKEN="$(sed -n 's/^SHIORI_DAV_TOKEN="\{0,1\}\([^"]*\)"\{0,1\}$/\1/p' "$ENVFILE")"
fi
if [ -z "$DAV_TOKEN" ] || ! dav_ok "$DAV_USER" "$DAV_TOKEN"; then
  log "creating app token for $DAV_USER (expiry $TOKEN_TTL)"
  DAV_TOKEN="$(create_token "$DAV_USER")"
  retry_dav "$DAV_USER" "$DAV_TOKEN" 20 || { log "new app token for $DAV_USER does not authenticate"; exit 1; }
fi

{
  echo "SHIORI_DAV_URL=$BASE/remote.php/webdav/"
  echo "SHIORI_DAV_USER=$DAV_USER"
  echo "SHIORI_DAV_TOKEN=\"$DAV_TOKEN\""
  if [ "$MODE" = https ]; then
    echo "SHIORI_DAV_INSECURE=1"
    echo "SHIORI_DAV_CA=$CA"
  fi
} > "$ENVFILE.tmp"
mv "$ENVFILE.tmp" "$ENVFILE"

log "ready: $BASE (pid $(cat "$PIDFILE")); wrote $ENVFILE"
cat "$ENVFILE"
